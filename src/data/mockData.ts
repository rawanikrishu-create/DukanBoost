// Generates relative time string based on date
export function getRelativeTimeString(dateStr: string): string {
  const now = new Date('2026-09-26T03:54:00');
  const past = new Date(dateStr);
  const diffHours = Math.floor((now.getTime() - past.getTime()) / (1000 * 60 * 60));
  const diffDays = Math.floor(diffHours / 24);

  if (diffHours < 2) return 'Just now';
  if (diffHours < 24) return 'Today';
  if (diffDays === 1) return 'Yesterday';
  if (diffDays < 7) return `${diffDays} days ago`;
  if (diffDays < 30) return `${Math.floor(diffDays / 7)} weeks ago`;
  return `${Math.floor(diffDays / 30)} months ago`;
}

// Format phone for privacy: +91 98XXX XX345
export function formatMaskedPhone(phone: string): string {
  const digits = phone.replace(/[^0-9]/g, '');
  if (digits.length >= 10) {
    const last10 = digits.slice(-10);
    return `+91 ${last10.slice(0, 2)}••• ••${last10.slice(7)}`;
  }
  return phone;
}

export function formatIndianCurrency(amount: number): string {
  return new Intl.NumberFormat('en-IN', {
    style: 'currency',
    currency: 'INR',
    maximumFractionDigits: 0,
  }).format(amount);
}

